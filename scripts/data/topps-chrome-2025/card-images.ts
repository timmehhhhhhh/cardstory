/**
 * SportsCardsPro (sportscardspro.com, PriceCharting's sister site for sports
 * cards -- see src/lib/pricing/sportscardspro/client.ts) product-photo
 * references for every 2025-26 Topps Chrome Basketball card, keyed by
 * cardNumber.
 *
 * Why SportsCardsPro and not TCDB: TCDB (tcdb.com) has a scan of every
 * card, but its image host sends a Cross-Origin-Resource-Policy header
 * that Chrome enforces against ANY cross-origin <img> embed -- confirmed
 * live in this app (Explore) via a net::ERR_BLOCKED_BY_RESPONSE.NotSameOrigin
 * console error, not just a bulk-loading/rate-limit issue like the one
 * already documented in scripts/data/lamelo-ball/2022-23.ts. SportsCardsPro
 * hosts its own product photo per card *and per named parallel* on
 * storage.googleapis.com/images.pricecharting.com/<imageId>/<size>.jpg,
 * which sends no such header and embeds normally.
 *
 * Per this checklist's "one photo per checklist group" design (see
 * imageIsInherited on SportsCardItem), only two photos are needed per base
 * card: the base card's own photo, and -- for the 50 cards TCDB flags
 * hasImageVariation -- a second, distinct photo for the "Image Variation"
 * tier. BASE_CARD_IMAGES covers all 299 base cards; IMAGE_VARIATION_IMAGES
 * covers the 50 Image Variation cards, confirmed to match
 * base-set.ts's hasImageVariation flag exactly (see the assertion in
 * seed-topps-chrome-2025.ts).
 *
 * sportscardspro.com blocks scripts/import-card-set.ts's plain fetch() with
 * a bot challenge (403) just like TCDB, so none of this could be scraped
 * as a normal profile-driven import. Each entry here was instead resolved
 * from the Browser pane, one product page per card: `slug` is
 * sportscardspro.com's own URL slug for that product (usually a simple
 * slugified player name + card number, but not always -- accents,
 * apostrophes, periods, and suffixes are handled inconsistently by their
 * own slugs, so the *exact* slug is kept verbatim rather than derived by a
 * formula) and `imageId` is the opaque id in their image CDN path.
 */
export const SPORTSCARDSPRO_GAME_SLUG = "basketball-cards-2025-topps-chrome";

export interface SportsCardsProImageRef {
  imageId: string;
  /** Exact sportscardspro.com URL slug for this product -- kept verbatim, not derived. */
  slug: string;
}

export function sportsCardsProImageUrl(ref: SportsCardsProImageRef): string {
  return `https://storage.googleapis.com/images.pricecharting.com/${ref.imageId}/1600.jpg`;
}

export function sportsCardsProSourceUrl(ref: SportsCardsProImageRef): string {
  return `https://www.sportscardspro.com/game/${SPORTSCARDSPRO_GAME_SLUG}/${ref.slug}`;
}

